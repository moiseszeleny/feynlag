"""Where results live: per-point data in ``cache/``, summaries in ``results/``.

Every results file of this project is a JSON object whose bulk is one
``points`` array (one entry per scan point, or per configuration); the rest is
a summary of a few kB: cut flow, conventions, counts. `research/README.md` asks
for committed files under ~100 kB, so the two halves are stored apart:

- ``cache/<name>.json`` holds the full payload, points included.  It is
  gitignored and regenerated by ``python run_pipeline.py``.
- ``results/<name>.json`` holds the same payload *without* ``points``, plus
  ``points_cache`` (where the points are), ``n_points_cached`` and
  ``points_sha256`` (the SHA-256 of the cache file).  It is committed, keeps the
  file name and every key the old single file had, so readers of the summary
  (`report_numbers.py`, the notebooks' summary reads) did not change.

The heavy loops that produce per-point *intermediate* objects (numpy arrays,
nested dicts the notebooks plot from) are not JSON results; the ``compute_*.py``
scripts pickle them with `save_raw`, and the notebooks load them back with
`load_raw` into the same variable names their old in-notebook loops filled.

All paths are anchored on this folder, not on the working directory.
"""

from __future__ import annotations

import hashlib
import json
import pickle
import warnings
from pathlib import Path

HERE = Path(__file__).resolve().parent
CACHE = HERE / "cache"
RESULTS = HERE / "results"

REGENERATE = "regenerate it with `python run_pipeline.py` (in research/thdm_s3)"

__all__ = ["write", "points", "full", "summary", "save_raw", "load_raw",
           "cache_path", "raw_path", "sha256", "CACHE", "RESULTS"]


def cache_path(name: str) -> Path:
    """``cache/<name>.json``."""
    return CACHE / f"{name}.json"


def raw_path(name: str) -> Path:
    """``cache/<name>.pkl``."""
    return CACHE / f"{name}.pkl"


def sha256(path: Path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def write(name: str, payload: dict, **dumps_kwargs) -> Path:
    """Write ``payload`` in full to ``cache/`` and its summary to ``results/``.

    ``dumps_kwargs`` go to `json.dumps` for the cache file, so each writer keeps
    the formatting (indentation, rounding hooks) it had.  The summary is always
    indented by 1 and is what git sees.  Returns the summary's path.
    """
    if "points" not in payload:
        raise KeyError(f"{name}: payload has no 'points' array to move to cache/")
    CACHE.mkdir(exist_ok=True)
    RESULTS.mkdir(exist_ok=True)
    full_path = cache_path(name)
    full_path.write_text(json.dumps(payload, **dumps_kwargs))
    summ = {k: v for k, v in payload.items() if k != "points"}
    summ["points_cache"] = f"cache/{name}.json"
    summ["n_points_cached"] = len(payload["points"])
    summ["points_sha256"] = sha256(full_path)
    out = RESULTS / f"{name}.json"
    out.write_text(json.dumps(summ, indent=1, ensure_ascii=False,
                              default=dumps_kwargs.get("default")) + "\n")
    return out


def summary(name: str) -> dict:
    """The committed summary ``results/<name>.json``."""
    return json.loads((RESULTS / f"{name}.json").read_text())


def full(name: str) -> dict:
    """The full payload ``cache/<name>.json``, checked against its summary's hash.

    A missing cache file raises with the regeneration hint.  A hash that differs
    from the committed summary only warns: outputs rounded to a few significant
    figures can change in the last digit across numpy versions, and that is a
    thing to report, not a reason to stop.
    """
    path = cache_path(name)
    if not path.exists():
        raise FileNotFoundError(f"{path.relative_to(HERE)} is missing; {REGENERATE}")
    expected = summary(name).get("points_sha256") if (RESULTS / f"{name}.json").exists() else None
    if expected is not None and sha256(path) != expected:
        warnings.warn(f"{path.relative_to(HERE)} does not match the hash in "
                      f"results/{name}.json: the cache was regenerated by different code "
                      f"or a different environment", stacklevel=2)
    return json.loads(path.read_text())


def points(name: str) -> list:
    """The per-point array of ``cache/<name>.json``."""
    return full(name)["points"]


def save_raw(name: str, obj) -> Path:
    """Pickle a compute script's raw output to ``cache/<name>.pkl``."""
    CACHE.mkdir(exist_ok=True)
    path = raw_path(name)
    with path.open("wb") as fh:
        pickle.dump(obj, fh, protocol=pickle.HIGHEST_PROTOCOL)
    return path


def load_raw(name: str):
    """Load ``cache/<name>.pkl`` (written by a ``compute_*.py`` script)."""
    path = raw_path(name)
    if not path.exists():
        raise FileNotFoundError(f"{path.relative_to(HERE)} is missing; {REGENERATE}")
    with path.open("rb") as fh:
        return pickle.load(fh)
