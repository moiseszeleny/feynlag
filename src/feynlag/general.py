"""The most general Lagrangian of a field content, and what a model leaves out.

:mod:`feynlag.suggest` enumerates the invariant operators a field content
admits.  This module turns that enumeration into the front door of model
building:

- :func:`most_general_lagrangian` — every renormalisable (or, with
  ``max_dim=5``, Weinberg) operator, each with a named coupling of the right
  mass dimension, plus the kinetic terms: a ready-to-use
  :class:`~feynlag.lagrangian.Lagrangian`.
- :func:`term_coverage` — decompose a model's *hand-written* potential and
  Yukawa sector on that operator basis and report which invariants it
  contains, which it leaves out, and anything it contains that the basis
  cannot express.

A missing operator is not an error — one may well want less than the most
general model — but it should be a choice, not an oversight: an operator the
symmetries allow is generated by renormalisation whether or not it was
written down.
"""

from dataclasses import dataclass, field as dc_field

import sympy as sp

from .dirac import diracC, diracPL, diracPR
from .fields import Fermion, Scalar
from .parameters import ExternalParameter
from .suggest import suggest_potential, suggest_yukawa
from .terms import FL_I, FL_J
from .vertices.bilinear import Bilinear, MajoranaBilinear, expand_bilinear
from .vertices.extract import extract_interaction_coefficients

__all__ = ["GeneralLagrangian", "TermCoverage", "most_general_lagrangian",
           "term_coverage"]

#: default coupling-name prefixes, by sector and mass dimension
_PREFIX = {("potential", 2): "m2_", ("potential", 3): "mu_",
           ("potential", 4): "lam_", ("yukawa", 3): "M_", ("yukawa", 4): "y_",
           ("yukawa", 5): "c_"}

_CPL = diracC * diracPL
_CPR = diracC * diracPR


def _fermion_halves(expr):
    """Split a hermitian fermion operator ``O + O†`` into ``(O, O†)``.

    ``O`` is the half built on ``P_R`` (Dirac: ``F̄_L P_R F_R``) or ``C P_L``
    (Majorana: ``Fᵀ C P_L F``); the other half is its conjugate.
    """
    expr = sp.expand(expr)
    op, hc = sp.S.Zero, sp.S.Zero
    for term in sp.Add.make_args(expr):
        gammas = {b.gamma for b in term.atoms(Bilinear, MajoranaBilinear)}
        if gammas and gammas <= {diracPR, _CPL}:
            op += term
        else:
            hc += term
    return op, hc


def _fermion_bases(expr):
    bases = set()
    for b in expr.atoms(Bilinear):
        bases |= {b.bar.base, b.field.base}
    for b in expr.atoms(MajoranaBilinear):
        bases |= {b.field1.base, b.field2.base}
    return bases


@dataclass
class GeneralLagrangian:
    """Result of :func:`most_general_lagrangian`.

    Attributes:
        lagrangian: the :class:`~feynlag.lagrangian.Lagrangian` (kinetic
            terms included unless ``kinetic=False``).
        parameters: the generated scalar couplings
            (:class:`~feynlag.parameters.ExternalParameter`, with the mass
            dimension the operator needs).
        flavour_matrices: generated :class:`~sympy.IndexedBase` Yukawa
            matrices (fermions with more than one flavour).
        terms: ``[(coupling, SuggestedTerm)]`` in Lagrangian order.
    """

    lagrangian: object
    parameters: list = dc_field(default_factory=list)
    flavour_matrices: list = dc_field(default_factory=list)
    terms: list = dc_field(default_factory=list)

    def __str__(self):
        rows = [f"  {str(getattr(c, 'name', c)):10s} dim {t.dim}  "
                f"[{t.sector}]  {t.label}{' + h.c.' if t.hc_added else ''}"
                for c, t in self.terms]
        return "\n".join([f"most general Lagrangian: {len(self.terms)} "
                          f"operators"] + rows)

    __repr__ = __str__


def most_general_lagrangian(fields, gauge_groups, discrete_groups=(),
                            names=None, max_dim=4, kinetic=True, verify=True):
    """Every invariant operator of ``fields``, each with a named coupling.

    The potential is ``V = Σ c_k O_k`` (so ``L ⊃ −c_k O_k``) and the Yukawa
    sector ``L ⊃ −(y O + h.c.)``, matching :func:`feynlag.terms.yukawa`; the
    dim-5 Weinberg operator enters as ``+(c O + h.c.)``, matching
    :func:`feynlag.terms.weinberg`.

    Couplings are named by type — ``m2_k`` (dimension-2 mass terms), ``mu_k``
    (cubic), ``lam_k`` (quartic), ``M_k`` (bare fermion mass), ``y_k``
    (Yukawa), ``c_k`` (dim 5) — and carry the mass dimension ``4 − dim``.
    A Yukawa between fermions with more than one flavour gets a flavour
    matrix ``y_k[i, j]`` (an :class:`~sympy.IndexedBase`).

    Args:
        fields: the scalars and fermions (gauge bosons are ignored).
        gauge_groups, discrete_groups: the symmetries to impose.
        names: ``{operator label: coupling name}`` overriding the defaults
            (the labels are printed by the returned object).
        max_dim: ``4`` (renormalisable) or ``5`` (adds the Weinberg operator).
        kinetic: also add ``(D_μφ)†(D^μφ)`` and the fermion gauge currents.
        verify: run the invariance oracle on every operator (default).

    Note:
        A potential operator that needed ``+ h.c.`` gets one **real**
        coupling: the CP-odd combination ``i(O − O†)`` is not enumerated.

    Returns:
        :class:`GeneralLagrangian`.
    """
    from .lagrangian import Lagrangian

    names = names or {}
    scalars = [f for f in fields if isinstance(f, Scalar)]
    fermions = [f for f in fields if isinstance(f, Fermion)]
    flavours = {}
    for f in fermions:
        for comp, bar in zip(f.components, f.bar_components):
            flavours[comp] = flavours[bar] = f.nflavors

    suggested = []
    if scalars:
        suggested += suggest_potential(scalars, gauge_groups, discrete_groups,
                                       max_dim=min(max_dim, 4), verify=verify)
    if fermions:
        suggested += suggest_yukawa(fermions, scalars, gauge_groups,
                                    discrete_groups,
                                    flavor_indices=(FL_I, FL_J),
                                    max_dim=max_dim, verify=verify)

    L = Lagrangian()
    out = GeneralLagrangian(L)
    counters = {}
    for term in suggested:
        prefix = _PREFIX.get((term.sector, term.dim), "c_")
        counters[prefix] = counters.get(prefix, 0) + 1
        name = names.get(term.label, f"{prefix}{counters[prefix]}")
        if term.sector == "potential":
            coupling = ExternalParameter(name, unit_dim=4 - term.dim)
            out.parameters.append(coupling)
            L.add(-coupling.s * term.expr, sector="potential",
                  name=term.label)
        else:
            sign = 1 if term.dim == 5 else -1
            multi = any(flavours.get(b, 1) > 1
                        for b in _fermion_bases(term.expr))
            if multi:
                coupling = sp.IndexedBase(name)
                op, hc = _fermion_halves(term.expr)
                c = coupling[FL_I, FL_J]
                expr = sign * (c * op + sp.conjugate(c) * hc)
                out.flavour_matrices.append(coupling)
            else:
                coupling = ExternalParameter(name, unit_dim=4 - term.dim)
                expr = sign * coupling.s * term.expr.xreplace({FL_J: FL_I})
                out.parameters.append(coupling)
            L.add(expand_bilinear(sp.expand(expr)), sector="yukawa",
                  name=term.label)
        out.terms.append((coupling, term))

    if kinetic:
        L.add_kinetic(*scalars, *fermions)
    return out


