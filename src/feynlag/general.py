@dataclass
class TermCoverage:
    """Result of :func:`term_coverage`.

    Attributes:
        present: ``[(SuggestedTerm, coefficient)]`` — the invariants the model
            contains, with the coefficient multiplying each (``V = Σ c O``
            for the potential, ``L = −Σ c O`` for the fermion sector).
        missing: ``[SuggestedTerm]`` — invariants the symmetries allow that
            the model does not contain.
        unmatched: ``{sector: expression}`` — what is left of a sector after
            removing its projection on the basis.  Non-zero means the sector
            contains something the basis does not: a non-invariant term, a
            CP-odd combination ``i(O − O†)`` (complex coupling), an operator
            above ``max_dim``, or explicit integer flavour indices.
    """

    present: list = dc_field(default_factory=list)
    missing: list = dc_field(default_factory=list)
    unmatched: dict = dc_field(default_factory=dict)

    @property
    def complete(self):
        """True iff no allowed invariant is missing."""
        return not self.missing

    def __str__(self):
        lines = [f"term coverage: {len(self.present)} present, "
                 f"{len(self.missing)} missing"]
        for term, coeff in self.present:
            lines.append(f"  present  {term.label}"
                         f"{' + h.c.' if term.hc_added else ''}"
                         f"   coefficient {coeff}")
        for term in self.missing:
            lines.append(f"  MISSING  {term.label}"
                         f"{' + h.c.' if term.hc_added else ''}"
                         f"   [{term.sector}, dim {term.dim}]")
        for sector, expr in self.unmatched.items():
            lines.append(f"  unmatched in {sector}: {expr}")
        return "\n".join(lines)

    __repr__ = __str__


def _vector(expr, registry, field_symbols):
    """``{monomial: coefficient}`` of ``expr`` in the field variables.

    Field variables are the scalar components, their conjugates and the
    fermion bilinears (the last two replaced by Dummies shared through
    ``registry``); everything else — couplings, ``conjugate(coupling)`` —
    stays in the coefficients.
    """
    expr = sp.expand(expr)
    for node in expr.atoms(sp.conjugate):
        if node.args[0] in field_symbols:
            registry.setdefault(node, sp.Dummy(f"conj_{len(registry)}"))
    for node in expr.atoms(Bilinear, MajoranaBilinear):
        registry.setdefault(node, sp.Dummy(f"bil_{len(registry)}"))
    norm = expr.xreplace(registry)
    variables = [s for s in norm.free_symbols
                 if s in field_symbols or s in set(registry.values())]
    vector = {}
    for terms in extract_interaction_coefficients(norm, variables).values():
        for key, coeff in terms.items():
            vector[key] = vector.get(key, sp.S.Zero) + coeff
    vector.pop((), None)
    return vector


def _canonical_fermion_half(expr):
    """The ``P_R`` / ``C P_L`` half of a fermion sector, with the canonical
    flavour indices: bar (first) leg ``FL_I``, field (second) leg ``FL_J``.

    Gauge currents (``γ^μ`` structures) and the conjugate half are dropped;
    hermiticity is checked separately by ``check_invariance``.  A bilinear
    carrying an explicit integer index is left as written.
    """
    expr = expand_bilinear(sp.expand(expr))
    out = sp.S.Zero
    for term in sp.Add.make_args(expr):
        atoms = list(term.atoms(Bilinear, MajoranaBilinear))
        if len(atoms) != 1 or atoms[0].gamma not in (diracPR, _CPL):
            continue
        b = atoms[0]
        legs = (b.bar, b.field) if isinstance(b, Bilinear) \
            else (b.field1, b.field2)
        idx = [leg.indices[0] for leg in legs]
        if any(i.is_number for i in idx):
            out += term
            continue
        coeff = sp.cancel(term / b)
        if idx[0] == idx[1]:
            # a flavour-universal term ψ̄_i χ_i: one shared index
            sub = {idx[0]: FL_I}
            canon = type(b)(legs[0].base[FL_I], b.gamma, legs[1].base[FL_I])
        else:
            sub = {idx[0]: FL_I, idx[1]: FL_J}
            canon = type(b)(legs[0].base[FL_I], b.gamma, legs[1].base[FL_J])
        out += coeff.xreplace(sub) * canon
    return out


def _decompose(model_expr, basis_exprs, field_symbols):
    """Coefficients of ``model_expr`` on the basis, and the remainder.

    Least squares on the monomial vectors: the basis is linearly independent
    by construction, so ``a = (BᵀB)⁻¹Bᵀv`` is exact when ``v`` lies in its
    span, and ``v − Ba`` is what the basis cannot express.
    """
    registry = {}
    vectors = [_vector(b, registry, field_symbols) for b in basis_exprs]
    v = _vector(model_expr, registry, field_symbols)
    keys = sorted({k for vec in vectors + [v] for k in vec}, key=str)
    if not keys:
        return [sp.S.Zero] * len(basis_exprs), sp.S.Zero
    B = sp.Matrix([[vec.get(k, 0) for vec in vectors] for k in keys])
    rhs = sp.Matrix([v.get(k, 0) for k in keys])
    if not basis_exprs:
        coeffs, rest = [], rhs
    else:
        sol = (B.T * B).LUsolve(B.T * rhs)
        coeffs = [sp.simplify(c) for c in sol]
        rest = (rhs - B * sol).applyfunc(sp.simplify)
    inverse = {d: node for node, d in registry.items()}
    remainder = sp.S.Zero
    for key, r in zip(keys, rest):
        if r != 0:
            remainder += r * sp.Mul(*[inverse.get(s, s) for s in key])
    return coeffs, remainder


def term_coverage(model, max_dim=4):
    """Which allowed invariants a model's Lagrangian contains.

    The potential (sector ``potential``) and the fermion mass/Yukawa terms
    (sectors ``yukawa`` and ``other``) are decomposed on the operator basis
    of :func:`~feynlag.suggest.suggest_potential` /
    :func:`~feynlag.suggest.suggest_yukawa` for the model's own fields and
    declared symmetries.

    Fermion terms are compared on their ``P_R`` (or ``C P_L``) half with
    canonical flavour indices, so a coupling may be a scalar or a flavour
    matrix; write Yukawas with the two legs' flavour indices on the bar and
    field legs as :func:`feynlag.terms.yukawa` does.

    Args:
        max_dim: ``4`` (default) or ``5`` to include the Weinberg operator.

    Returns:
        :class:`TermCoverage`.
    """
    scalars = [f for f in model.fields if isinstance(f, Scalar)]
    fermions = [f for f in model.fields if isinstance(f, Fermion)]
    field_symbols = {c for f in scalars for c in f.components}
    report = TermCoverage()

    if scalars:
        basis = suggest_potential(scalars, model.gauge_groups,
                                  model.discrete_groups,
                                  max_dim=min(max_dim, 4), verify=False)
        coeffs, rest = _decompose(model.potential, [t.expr for t in basis],
                                  field_symbols)
        for term, c in zip(basis, coeffs):
            (report.present.append((term, c)) if c != 0
             else report.missing.append(term))
        if rest != 0:
            report.unmatched["potential"] = rest

    if fermions:
        basis = suggest_yukawa(fermions, scalars, model.gauge_groups,
                               model.discrete_groups,
                               flavor_indices=(FL_I, FL_J), max_dim=max_dim,
                               verify=False)
        sector = sp.Add(*[t.expr for t in model.lagrangian.terms
                          if t.sector in ("yukawa", "other")])
        halves = [_fermion_halves(t.expr)[0] for t in basis]
        # L ⊃ −c·O for dim ≤ 4, +c·O for the dim-5 operator
        signed = [(-1 if t.dim <= 4 else 1) for t in basis]
        model_half = _canonical_fermion_half(sector)
        # a flavour-universal model term ψ̄_i χ_i is the i = j restriction of
        # the basis operator, so it is decomposed against that restriction;
        # terms with two leg indices against the operator itself
        matrix_part = sp.Add(*[t for t in sp.Add.make_args(model_half)
                               if t.has(FL_J)])
        universal_part = sp.expand(model_half - matrix_part)
        c_mat, rest_mat = _decompose(matrix_part, halves, field_symbols)
        c_uni, rest_uni = _decompose(
            universal_part, [h.xreplace({FL_J: FL_I}) for h in halves],
            field_symbols)
        for term, cm, cu, s in zip(basis, c_mat, c_uni, signed):
            c = sp.simplify(s * (cm + cu))
            (report.present.append((term, c)) if c != 0
             else report.missing.append(term))
        rest = rest_mat + rest_uni
        if rest != 0:
            report.unmatched["yukawa"] = rest
    return report
